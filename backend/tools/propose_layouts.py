"""U4 onboarding pipeline: cluster T3-clean files by structure and emit a
draft LayoutSpec source + gate report per cluster of >=MIN_CLUSTER files.
Registers nothing — output lives under comparison/universal/proposals/
(untracked). A proposal is a STARTING POINT for a hand-reviewed spec; T3
success alone never promotes a layout to serving.

Fingerprint = sorted header tokens + money-role set + date shape + amount
form. Gate report checks: cluster size (10+), bank consistency (one detector
bank dominating; collisions flagged), hold-out stability (60/40 split by sha —
fingerprint must hold on both halves, which it does by construction, so the
real signal is verdict/row-count dispersion), and cross-bank bleed (same
fingerprint claimed by >=2 banks above 5% each -> flag, never auto-onboard).

Usage:
    python -m tools.propose_layouts u3a.jsonl [u3b.jsonl ...]
"""
from __future__ import annotations

import hashlib
import json
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BACKEND = ROOT / "backend"
sys.path.insert(0, str(BACKEND))
OUTDIR = ROOT / "comparison" / "universal" / "proposals"
MIN_CLUSTER = 10
TOP_N = 20


def fingerprint(rec: dict) -> str:
    inf = rec.get("univ", {}).get("infer", {})
    header = inf.get("header_tokens") or "implicit"
    header = " ".join(sorted(str(header).split()))
    key = f"{header}::{inf.get('money','')}::{inf.get('date_shape','')}::{inf.get('amount_form','')}"
    return hashlib.sha256(key.encode()).hexdigest()[:12], key


def _spec_source(fp: str, key: str, members) -> str:
    inf = members[0].get("univ", {}).get("infer", {})
    tokens = (inf.get("header_tokens") or "").split()
    money = sorted((inf.get("money") or "").split("/"))
    return f'''"""DRAFT LayoutSpec proposal fp={fp} — generated by tools/propose_layouts.py.

UNREGISTERED. Review against real files, then hand-author the real spec under
extractors/<bank>/layout_spec.py. Do NOT register without the full evidence
gate (build/hold-out reconciliation, mutation probes, wrong-bank sweep,
end-to-end + workbook checks).
"""
from __future__ import annotations

import re

from app.services.statement_engine.extraction.layout_spec import LayoutSpec

# evidence from {len(members)} T3-clean files
# header tokens: {tokens}
# money roles:   {money}
# date shape:    {inf.get("date_shape")}
# amount form:   {inf.get("amount_form")}
# fingerprint:   {key}

SPEC = LayoutSpec(
    layout_id="proposed_{fp}",
    bank_key="proposed",
    bank_name="PROPOSED - review me",
    columns={{}},            # TODO: map header tokens to column roles
    text_columns=(),          # TODO
    debit_column="",          # TODO
    credit_column="",         # TODO
    balance_column="",        # TODO
    date_re=re.compile(r"^$"),  # TODO: date shape {inf.get("date_shape")}
    date_format="",           # TODO
    amount_re=re.compile(r"^$"),  # TODO
)
'''


def main(jsonl_paths) -> int:
    recs = []
    for fp in jsonl_paths:
        p = Path(fp)
        if not p.exists():
            p = ROOT / "comparison" / "universal" / fp
        if p.exists():
            for line in p.read_text(encoding="utf-8").splitlines():
                try:
                    recs.append(json.loads(line))
                except Exception:
                    pass
    clean = [r for r in recs if r.get("univ", {}).get("verdict") == "REVIEW"
             and r["univ"].get("row_keys")]
    print(f"{len(recs)} records, {len(clean)} T3-clean")

    clusters = defaultdict(list)
    keys = {}
    for r in clean:
        fp, key = fingerprint(r)
        clusters[fp].append(r)
        keys[fp] = key
    ranked = sorted(clusters.items(), key=lambda kv: -len(kv[1]))
    OUTDIR.mkdir(parents=True, exist_ok=True)
    lines = ["# Universal-reader layout proposals",
             f"T3-clean files: {len(clean)} | clusters: {len(ranked)} | "
             f"shown: top {TOP_N} (min {MIN_CLUSTER})", ""]
    shown = 0
    for fp, members in ranked:
        if len(members) < MIN_CLUSTER or shown >= TOP_N:
            continue
        shown += 1
        folders = Counter(m["folder"] for m in members)
        banks = Counter(m.get("folder", "?") for m in members)
        rows_n = [m["univ"].get("rows", 0) for m in members]
        inf = members[0].get("univ", {}).get("infer", {})
        ms = sorted(members, key=lambda m: m["sha"])
        cut = int(len(ms) * 0.6)
        build, hold = ms[:cut], ms[cut:]
        # bank consistency: dominant folder share; a second bank >5% = bleed flag
        total = len(members)
        dom_name, dom_n = banks.most_common(1)[0]
        bleed = [(b, n) for b, n in banks.items() if b != dom_name and n / total > 0.05]
        gate = [
            f"G1 size>=10: PASS ({total})",
            f"G2 dominant bank share: {dom_n}/{total} ({dom_n/total:.0%})" + (" PASS" if dom_n / total >= 0.9 else " HOLD"),
            f"G3 build/hold-out {len(build)}/{len(hold)}: fingerprints stable by construction",
            f"G4 cross-bank bleed: " + (f"FLAG {bleed}" if bleed else "none PASS"),
            f"G5 row-count dispersion: median {int(statistics.median(rows_n))} p10 {int(sorted(rows_n)[len(rows_n)//10])} p90 {int(sorted(rows_n)[len(rows_n)*9//10])}",
            f"G6 evidence: detector bank + folder agreement required at onboarding review — NOT done here",
        ]
        (OUTDIR / f"proposal_{shown:02d}_{fp}.py").write_text(
            _spec_source(fp, keys[fp], members), encoding="utf-8")
        lines += [
            f"## Proposal {shown}: fp {fp} — {total} files (dominant: {dom_name})",
            f"- infer: {json.dumps({k: v for k, v in inf.items()}, default=str)[:260]}",
            *[f"- {g}" for g in gate],
            f"- spec draft: `proposal_{shown:02d}_{fp}.py`",
            f"- shas: {[m['sha'] for m in members[:20]]}{'...' if total > 20 else ''}",
            ""]
    (OUTDIR / "proposals_report.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {shown} proposals to {OUTDIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:] or ["u3a.jsonl", "u3b.jsonl"]))
